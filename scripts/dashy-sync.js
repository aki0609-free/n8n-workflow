#!/usr/bin/env node
/**
 * dashy/user-data/conf.yml を生成する。
 *
 *   npm run dashy:sync            生成して保存（Dashy は conf.yml をリクエストごとに読み直すため再起動不要）
 *   npm run dashy:sync -- --stdout 保存せずに標準出力へ
 */
const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const { buildDashyConfig, validateCategories } = require('./lib/dashy');
const { parseFrontMatter } = require('./lib/design-doc');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'dashy', 'user-data');
const OUT = path.join(OUT_DIR, 'conf.yml');
const toStdout = process.argv.includes('--stdout');

const readYaml = (rel) => YAML.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));

const dashboard = readYaml('config/dashboard.yml');
const { categories = [] } = readYaml('config/categories.yml');

const categoryErrors = validateCategories(categories);
if (categoryErrors.length > 0) {
  console.error('config/categories.yml にエラーがあります:');
  for (const e of categoryErrors) console.error(`  - ${e}`);
  process.exit(1);
}

const workflowDir = path.join(ROOT, 'workflows');
const workflows = fs
  .readdirSync(workflowDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const name = path.basename(f, '.json');
    const workflow = JSON.parse(fs.readFileSync(path.join(workflowDir, f), 'utf8'));
    const designRel = `designs/${name}.md`;
    const designAbs = path.join(ROOT, designRel);
    const design = fs.existsSync(designAbs)
      ? parseFrontMatter(fs.readFileSync(designAbs, 'utf8'))
      : null;
    return {
      name,
      workflow,
      hasSpec: fs.existsSync(path.join(ROOT, 'doc', 'specifications', `${name}.md`)),
      designPath: design ? designRel : null,
      summary: design && design.title ? design.title : null,
    };
  });

const { config, warnings } = buildDashyConfig({ dashboard, categories, workflows });
for (const w of warnings) console.error(`warning: ${w}`);

const header =
  '# AUTO-GENERATED by `npm run dashy:sync`. 直接編集しないでください。\n' +
  '# 元データ: config/dashboard.yml, config/categories.yml, workflows/*.json\n';
const body = header + YAML.stringify(config, { lineWidth: 0 });

if (toStdout) {
  process.stdout.write(body);
  process.exit(0);
}

fs.mkdirSync(OUT_DIR, { recursive: true });
// 同じディレクトリに書いてから rename（Dashy が書きかけのファイルを読まないように）
const tmp = path.join(OUT_DIR, `.conf.yml.${process.pid}.tmp`);
fs.writeFileSync(tmp, body);
fs.renameSync(tmp, OUT);

const count = workflows.length;
const sectionCount = config.sections.length;
console.log(
  `dashy/user-data/conf.yml を更新しました（ワークフロー ${count} 件 / セクション ${sectionCount} 個）`,
);
